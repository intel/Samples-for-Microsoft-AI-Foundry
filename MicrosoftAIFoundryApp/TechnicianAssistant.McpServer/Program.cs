using Microsoft.EntityFrameworkCore;
using TechnicianAssistant.McpServer.Data;

var builder = WebApplication.CreateBuilder(args);

// ?? Database ???????????????????????????????????????????????????????????????
var dbPath = builder.Configuration["DatabasePath"] ?? "parts.db";
builder.Services.AddDbContext<PartsDbContext>(opt =>
    opt.UseSqlite($"Data Source={dbPath}"));

// ?? MCP Server ?????????????????????????????????????????????????????????????
builder.Services.AddMcpServer()
    .WithHttpTransport()
    .WithToolsFromAssembly();

var app = builder.Build();

// ?? Seed database on startup ???????????????????????????????????????????????
using (var scope = app.Services.CreateScope())
{
    var db = scope.ServiceProvider.GetRequiredService<PartsDbContext>();
    await DbSeeder.SeedAsync(db);
}

app.MapMcp("/mcp");

app.Run();
